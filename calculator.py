a = int(input("Enter first value :"))
b = int(input("Enter second value :"))

sum = a + b  # a = 6 , b = 3 => 9

sub = a - b  # a = 6 , b = 3 => 3

mul = a * b  # a = 6 , b = 3 => 18

div = a / b  # a = 6 , b = 3 => 2

mod = a % b # a = 6 , b = 3 => divide => reminder 5/3 = 2

print(f"Addition  =  {sum}")
print(f"Substraction  =  {sub}")
print(f"Multiplication  =  {mul}")
print(f"Division  =  {div}")
print(f"Mode  =  {mod}")


